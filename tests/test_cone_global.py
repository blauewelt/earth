# taken from the code as it stood BEFORE the wrap and the group support were
# written (2026-09-04). Every array, its dtype, its shape and its bytes.
NA_DIGEST = "6042073e1a20f00d9e233e16570920ba366dfe359fe13a97eaab51c8162d0180"

NA_CHANS = ["cur_speed", "log_mld", "ssh", "tau_x", "tau_y", "tau_x_std",
            "tau_y_std", "sst", "cur_u", "cur_v", "rg_t300", "rg_s300"]


def _na_fixture():
    """Family 4's window (lat 0..70, lon -100..20 at 0.25 deg), random."""
    rng = np.random.default_rng(20260904)
    T, H, W, C = 40, 281, 481, len(NA_CHANS)
    X = rng.normal(size=(T, H, W, C)).astype(np.float32)
    X[rng.random(X.shape) < 0.05] = np.nan
    lats = 0.0 + 0.25 * np.arange(H)
    lons = -100.0 + 0.25 * np.arange(W)
    return X, lats, lons


def _na_anchors():
    rng = np.random.default_rng(7)
    a = np.stack([rng.integers(6, 38, 64), rng.integers(0, 281, 64),
                  rng.integers(0, 481, 64)], axis=1).astype(np.int64)
    a[0] = [20, 140, 0]                       # hard against the west edge
    a[1] = [20, 140, 480]                     # hard against the east edge
    a[2] = [20, 0, 240]                       # hard against the south edge
    a[3] = [20, 280, 240]                     # hard against the north edge
    return a


def _digest(out):
    h = hashlib.sha256()
    for k in sorted(out):
        a = np.ascontiguousarray(out[k])
        h.update(k.encode())
        h.update(str(a.dtype).encode())
        h.update(str(a.shape).encode())
        h.update(a.tobytes())
    return h.hexdigest()


# ============================================================ 1. the wrap ==
def test_wrap_is_measured_from_the_lon_axis_not_declared():
    """`wrap` is a property of the tensor, and there is no flag to get wrong.

    481 columns of 0.25 deg span 120.25 deg and the axis does not close; 1440
    of them span exactly 360 and it does. The constructor computes that, so a
    caller cannot hand the North Atlantic window a `wrap=True` and cannot
    forget it on the globe.
    """
    for W, lon0, want in ((481, -100.0, False), (1440, -180.0, True),
                          (720, -180.0, False),   # 0.5 deg would close, 0.25
                                                  # does not
                          (360, -180.0, False)):
        X = np.zeros((2, 3, W, 1), np.float32)
        s = ConeSampler(X, np.isfinite(X), [0.0, 0.25, 0.5],
                        lon0 + 0.25 * np.arange(W), ["ssh"], L_in=1)
        assert s.wrap is want, (W, lon0)
    # and a HALF-degree global axis closes too — the rule is the arithmetic,
    # not the number 1440
    X = np.zeros((2, 3, 720, 1), np.float32)
    s = ConeSampler(X, np.isfinite(X), [0.0, 0.5, 1.0],
                    -180.0 + 0.5 * np.arange(720), ["ssh"], L_in=1,
                    dlat_deg=0.5)
    assert s.wrap is True


def test_north_atlantic_sample_is_bit_identical_to_before_the_wrap():
    """The window path did not move. Not "equivalent" — identical bytes.

    NA_DIGEST was taken from the sampler as it stood before this change; if
    the wrap, the `_read` indirection or the group routing altered ANY value,
    flag or coordinate on a non-wrapping tensor, this fails.
    """
    X, lats, lons = _na_fixture()
    s = ConeSampler(X, np.isfinite(X), lats, lons, NA_CHANS, L_in=6)
    assert s.wrap is False
    out = s.sample(_na_anchors())
    assert _digest(out) == NA_DIGEST, (
        "the North Atlantic sampling path changed. Every archived cone number "
        "was produced by the code this digest was taken from.")
    # and the edge anchors really did exercise the invalid branch, or the
    # comparison above is vacuous there
    assert not out["valid"][:4].all()


# ----------------------------------------------------- the global fixture --
GLOBAL_NY, GLOBAL_NX = 721, 1440


def _address_globe(T=8, chans=("ssh",)):
    """A global tensor in which every cell holds its own (row, col) address.

    `code = row * 1440 + col` is at most 1,038,239, well inside float32's
    exact integer range, so "the value that came back" and "the cell the cone
    named" are literally comparable — `tests/test_cone_dot_path.py`'s trick,
    one grid larger.
    """
    y = np.arange(GLOBAL_NY, dtype=np.float32)[:, None]
    x = np.arange(GLOBAL_NX, dtype=np.float32)[None, :]
    code = (y * GLOBAL_NX + x)
    X = np.repeat(np.repeat(code[None, :, :, None], len(chans), axis=3),
                  T, axis=0).astype(np.float32)
    lats = -90.0 + 0.25 * np.arange(GLOBAL_NY)
    lons = -180.0 + 0.25 * np.arange(GLOBAL_NX)
    return np.ascontiguousarray(X), lats, lons, list(chans)


def test_a_dot_at_lon_minus_179_75_reads_the_plus_179_side():
    """The anchor sits in column 1 (lon -179.75). Its westward dots leave the
    axis and must come back at columns near 1439, with the VALUE of those
    cells — not zero, not the value of column 0 clamped, and not invalid."""
    X, lats, lons, chans = _address_globe()
    s = ConeSampler(X, np.isfinite(X), lats, lons, chans, L_in=6)
    assert s.wrap is True
    y, x, t = 504, 1, 7                                   # lat 36, lon -179.75
    out = s.sample(np.array([[t, y, x]], np.int64))
    R = s.row(y)
    want_col = (x + R["dx"]) % GLOBAL_NX
    want_row = y + R["dy"]
    # every dot is on the grid: latitude never leaves it at 36 N and longitude
    # cannot leave it at all
    assert out["valid"][0].all()
    got = out["vals"][0, :R["n"]]
    assert np.array_equal(got, (want_row * GLOBAL_NX + want_col)
                          .astype(np.float32))
    # the wrap actually happened: some dots are far to the east
    assert (want_col > 1400).sum() > 0
    # and the EXACT cells, spelled out for the first family-B lag so a reader
    # can check the arithmetic by hand: dx = -8 at column 1 is column 1433.
    by_lag = {}
    for l, dy, dx in zip(R["lag"], R["dy"], R["dx"]):
        by_lag.setdefault(int(l), []).append([y + int(dy),
                                              (x + int(dx)) % GLOBAL_NX])
    assert by_lag[1] == [[504, 1], [505, 1], [502, 5], [504, 1433],
                         [507, 8], [498, 1439], [510, 1435]]
    assert all(0 <= c < GLOBAL_NX for cells in by_lag.values()
               for _, c in cells)


def test_the_same_anchor_on_a_window_is_invalid_where_the_globe_wraps():
    """The control. Give the identical cone a NON-closing axis of the same
    width and the westward dots are off the tensor and read as invalid — which
    is what family 4 does and must keep doing."""
    X, lats, lons, chans = _address_globe()
    # 1200 columns of 0.25 deg span 300 deg: the axis does NOT close, whatever
    # its first value is. (Any 1440-wide 0.25 deg axis does, which is why the
    # control has to be narrower rather than merely shifted.)
    nx = 1200
    win = ConeSampler(np.ascontiguousarray(X[:, :, :nx]),
                      np.isfinite(X[:, :, :nx]), lats, lons[:nx], chans,
                      L_in=6)
    assert win.wrap is False
    out = win.sample(np.array([[7, 504, 1]], np.int64))
    R = win.row(504)
    off = (1 + R["dx"] < 0) | (1 + R["dx"] >= nx)
    assert off.sum() > 0
    assert not out["valid"][0, :R["n"]][off].any()
    assert (out["vals"][0, :R["n"]][off] == 0).all()


def test_the_lag0_patch_wraps_too():
    """`_patch` is the other place a column offset is applied. At column 0 the
    3x3's west column is 1439, and all nine cells are real."""
    X, lats, lons, chans = _address_globe()
    s = ConeSampler(X, np.isfinite(X), lats, lons, chans, L_in=1)
    out = s.sample(np.array([[3, 400, 0]], np.int64))
    got = out["patch_vals"][0, 0]
    want = np.array([[(400 + dy) * GLOBAL_NX + ((0 + dx) % GLOBAL_NX)]
                     for dy in (-1, 0, 1) for dx in (-1, 0, 1)],
                    np.float32).ravel()
    assert np.array_equal(got, want)
    assert out["patch_obs"][0, 0].all()
    assert 399 * GLOBAL_NX + 1439 in set(got.tolist())


def test_latitude_is_clipped_never_wrapped():
    """There is no cell north of the pole. A dot that leaves the latitude axis
    stays invalid even on a globe — E-071 §1's own rule, and the reason the
    near-pole case is a MEASUREMENT in cone_geometry.json rather than a fix."""
    X, lats, lons, chans = _address_globe()
    s = ConeSampler(X, np.isfinite(X), lats, lons, chans, L_in=6)
    y = GLOBAL_NY - 3                                   # lat 89.5
    out = s.sample(np.array([[7, y, 700]], np.int64))
    R = s.row(y)
    off = (y + R["dy"] >= GLOBAL_NY) | (y + R["dy"] < 0)
    assert off.sum() > 0, "the polar anchor did not reach off the axis"
    assert not out["valid"][0, :R["n"]][off].any()
    # nothing wrapped round to the far side: no dot's row is negative-modulo
    rows = (y + R["dy"])[~off]
    assert rows.min() >= 0 and rows.max() < GLOBAL_NY


# ================================================== 2. the coarse lookup ==
def _toy_groups(nx=1440, ny=721, T=4):
    """A two-group set whose coarse array holds its own (y1, x1) address."""
    dense = np.zeros((T, ny, nx, 1), np.float32)
    ny1, nx1 = 181, 360
    y1 = np.arange(ny1, dtype=np.float32)[:, None]
    x1 = np.arange(nx1, dtype=np.float32)[None, :]
    coarse = np.repeat((y1 * nx1 + x1)[None, :, :, None], T,
                       axis=0).astype(np.float32)
    g0 = Group("g025", dense, -90.0 + 0.25 * np.arange(ny),
               -180.0 + 0.25 * np.arange(nx), ["ssh"])
    g1 = Group("g100", coarse, np.arange(-90.0, 91.0),
               np.arange(-180.0, 180.0), ["t2m"])
    return GroupSet([g0, g1])


def test_the_coarse_factor_is_derived_from_the_lat_steps():
    gs = _toy_groups()
    assert [g.factor for g in gs.groups] == [1, 4]
    # and a group whose step is not a whole multiple is refused rather than
    # rounded into the nearest cell
    # 240 rows from pole to pole is a step of 180/239 = 0.7531 deg, i.e.
    # 3.01 master cells — not a whole number, so there is no cell the lookup
    # could name and the set refuses rather than rounding to 3.
    bad = Group("g033", np.zeros((4, 240, 480, 1), np.float32),
                np.linspace(-90, 90, 240), np.linspace(-180, 179.25, 480),
                ["t2m"])
    with pytest.raises(ValueError, match="whole number"):
        GroupSet([gs.groups[0], bad])


def test_coarse_lookup_at_x_1439_lands_on_x1_zero():
    """E-070 §1: `x1 = floor(x/4 + 0.5) mod 360`. Columns 1438 and 1439 round
    to 360 and wrap to 0, which is the same meridian as +180 — the one case
    the plan calls out, and the one a `min(..., nx1-1)` clamp would get wrong
    by putting them at 359.
    """
    from build_family7 import coarse_lookup
    gs = _toy_groups()
    s = ConeSampler(gs, None, gs.lats, gs.lons, gs.chan, L_in=1)
    nx1 = 360
    for x, want_x1 in ((1439, 0), (1438, 0), (1436, 359), (0, 0), (2, 1),
                       (4, 1), (6, 2)):
        v, _ = s.read_cells(np.int64(1), np.int64(360), np.int64(x),
                            np.array([1], np.int64))
        y1 = 90                                    # row 360 -> lat 0 -> y1 90
        assert float(v[0]) == y1 * nx1 + want_x1, (x, want_x1)
        # and it is the BUILDER's own lookup, not a second one
        by, bx = coarse_lookup(np.array([360]), np.array([x]))
        assert (int(by[0]), int(bx[0])) == (y1, want_x1)


def test_the_lag0_patch_serves_one_coarse_cell_nine_times():
    """E-070 D3, "served as the same cell": a 1 degree field sampled at 0.25
    degrees does not gain resolution from a 3x3 of 0.25 degree cells. Away
    from a coarse boundary all nine patch cells are the same coarse value —
    and the token shape is unchanged, which is the point."""
    gs = _toy_groups()
    s = ConeSampler(gs, None, gs.lats, gs.lons, gs.chan, L_in=1)
    out = s.sample(np.array([[2, 360, 200]], np.int64))     # x=200 -> x1=50
    patch = out["patch_vals"][0, 1]                          # channel 1 = t2m
    assert patch.shape == (9,)
    assert len(set(patch.tolist())) == 1
    assert patch[0] == 90 * 360 + 50
    # the dense channel is NOT collapsed: nine distinct cells, nine values
    assert out["patch_vals"][0, 0].shape == (9,)



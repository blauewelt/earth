#!/usr/bin/env python3
"""E-070 / E-071 Phase E · the cone on a GLOBE, and on a three-group tensor.

Two changes to `ml/cone_sampler.py` are under test here, and both are changes
of the same kind: the sampler stops asserting a property of the North Atlantic
window and starts READING the property off the tensor it was handed.

  1. **The dateline.** Whether the cell west of column 0 is column W-1 is a
     fact about the longitude axis — `W * dlon == 360` means the axis closes —
     not a policy. So `ConeSampler.wrap` is measured in the constructor: false
     for family 4's 481 x 0.25 deg = 120 deg window, where a wrap would put
     the Iberian shelf one cell west of Florida, and true for family 7's
     1440 x 0.25 deg = 360 deg globe, where refusing it would cut the Pacific
     in half. Latitude is still clipped and never wrapped.

  2. **Three groups at two resolutions.** Family 7 is `g025` (0.25 deg, 7
     channels), `g100` (1 deg, 14) and `rg100` (1 deg, 32, live Argo bins
     only). The cone is placed on the dense grid; a coarse channel is read at
     the coarse cell E-070 §1's lookup names; a live-bins channel is a miss
     token at every bin its group did not write. The TOKEN SCHEMA does not
     move — same `vals`/`obs`/`valid`, same count — because the group change
     is about where a value comes from, not how many there are.

The North Atlantic path must be BIT-IDENTICAL to what it was before either
change. That is pinned below by a digest taken from the pre-change code and
written into this file, not recomputed from the current one — a reference
generated by the thing it certifies certifies nothing.

    python3 -m pytest -q tests/test_cone_global.py

The multi-group half runs against a real family-7 tensor built by
`ml/build_family7.py --smoke`: synthetic sources, the whole builder, the full
721 x 1440 grid and five pentad bins, about twenty seconds. A toy GroupSet
assembled by hand would test this file's own idea of the layout; the smoke
tensor tests the layout the builder writes.
"""
